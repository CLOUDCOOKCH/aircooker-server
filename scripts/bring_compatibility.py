"""Credential-gated compatibility experiment on a dedicated disposable Bring! list.
This does not enable application mutations. Credentials are read from files.
"""

import asyncio
import json
import os
import time
from pathlib import Path
from uuid import uuid4


async def main():
    required = ("BRING_EMAIL_FILE", "BRING_PASSWORD_FILE", "BRING_TEST_LIST_ID")
    if (
        any(not os.environ.get(key) for key in required)
        or os.environ.get("BRING_DEDICATED_TEST_LIST") != "YES"
    ):
        raise SystemExit(
            "Skipped: provide credential file paths, BRING_TEST_LIST_ID and BRING_DEDICATED_TEST_LIST=YES"
        )
    import aiohttp
    from bring_api import Bring
    from bring_api.types import BringItemOperation

    list_id = os.environ["BRING_TEST_LIST_ID"]
    email = Path(os.environ["BRING_EMAIL_FILE"]).read_text().strip()
    password = Path(os.environ["BRING_PASSWORD_FILE"]).read_text().strip()
    async with aiohttp.ClientSession(timeout=aiohttp.ClientTimeout(total=20)) as session:
        bring = Bring(session, email, password)
        await bring.login()
        await bring.load_lists()
        baseline = await bring.get_list(list_id)
        original = {
            i.uuid: (i.itemId, i.specification)
            for i in baseline.items.purchase + baseline.items.recently
        }
        own_id = str(uuid4())
        name = "aircooker-compatibility-" + str(uuid4())[:8]
        item = {"uuid": own_id, "itemId": name, "spec": "one"}

        def lookup(response):
            return {i.uuid: i for i in response.items.purchase + response.items.recently}

        try:
            await bring.batch_update_list(list_id, item, BringItemOperation.ADD)
            await bring.batch_update_list(list_id, item, BringItemOperation.ADD)
            current = lookup(await bring.get_list(list_id))
            assert own_id in current and current[own_id].specification == "one"
            item["spec"] = "two"
            await bring.batch_update_list(list_id, item, BringItemOperation.ADD)
            assert lookup(await bring.get_list(list_id))[own_id].specification == "two"
            await bring.batch_update_list(list_id, item, BringItemOperation.COMPLETE)
            assert any(i.uuid == own_id for i in (await bring.get_list(list_id)).items.recently)
        finally:
            # Only the UUID generated by this invocation is removed.
            await bring.batch_update_list(list_id, item, BringItemOperation.REMOVE)
        after = lookup(await bring.get_list(list_id))
        assert own_id not in after
        assert all(
            i in after and (after[i].itemId, after[i].specification) == state
            for i, state in original.items()
        )
        report = os.environ.get("BRING_COMPATIBILITY_REPORT")
        if report:
            path = Path(report)
            with path.open("w") as out:
                json.dump(
                    {
                        "sdk_version": "1.1.2",
                        "list_id": list_id,
                        "verified_at": time.time(),
                        "passed": True,
                    },
                    out,
                )
            path.chmod(0o600)
        print(
            "PASS: UUID create, replay, update, completion and removal; baseline items preserved."
        )


if __name__ == "__main__":
    asyncio.run(main())
